// tools/homepage-preview/check.mjs — the homepage in a browser, fed controlled /organism and /health.
//
// Serves the working tree's homepage.html (byte for byte; the agent's no-JS fill is not applied here) on a local port
// with /organism and /health answered from fixture files, opens it in headless Chromium, and asserts what the page
// shows against the fixtures. Dev-only: it needs Playwright (install in this folder: npm install), and is not part of
// `bun run test`. Run from the repository root:
//   node tools/homepage-preview/check.mjs
// Exit 0 when every check passes, 1 otherwise. Prints one line per check.
//
// Scenarios (fixtures/): the operator's capture of 2026-10-21 07:27:27Z, and the four source modes generated by the
// deployed status rule (tagged _synthetic). Adversarial cases are built from them in this file:
//   ADJ  adjacent cycles: /organism and /health with identical labels and different observed_at → the reasons shown
//        are /organism's, the seeds line carries no /health detail (no "k of 3 configured seeds answered")
//   NOOC /health without on_chain_validators → "not reported", and no retained count (the digits 35 appear nowhere)
//   WATCH the watch round's own clock is shown beside the list-read clock when the watch is observed
import { createServer } from "node:http";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..");
const HOME = readFileSync(join(ROOT, "homepage.html"), "utf8");
const FX = join(here, "fixtures");
const load = (n) => JSON.parse(readFileSync(join(FX, n), "utf8"));
const { chromium } = await import("playwright");

let passed = 0, failed = 0;
const check = (name, cond, detail) => { if (cond) { passed++; console.log("  ok   " + name); } else { failed++; console.log("  FAIL " + name + (detail ? "  — " + String(detail).slice(0, 300) : "")); } };

// One server, answers switched per scenario.
let current = { organism: null, health: null };
const server = createServer((req, res) => {
  const p = new URL(req.url, "http://x").pathname;
  if (p === "/") { res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" }); return res.end(HOME); }
  if (p === "/organism" || p === "/health") {
    const d = current[p.slice(1)];
    if (d === null) { res.writeHead(503, { "Content-Type": "application/json" }); return res.end('{"error":"unavailable"}'); }
    res.writeHead(200, { "Content-Type": "application/json", "Cache-Control": "no-store" }); return res.end(JSON.stringify(d));
  }
  res.writeHead(404); res.end();
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const BASE = "http://127.0.0.1:" + server.address().port;

const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
async function render(organism, health, { width = 1280 } = {}) {
  current = { organism, health };
  const page = await browser.newPage({ viewport: { width, height: 900 } });
  await page.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
  await page.goto(BASE + "/");
  await page.waitForFunction(() => document.getElementById("panel").dataset.state !== "pending", null, { timeout: 10000 });
  await page.waitForTimeout(150);
  const out = await page.evaluate(() => {
    const t = (id) => (document.getElementById(id) || {}).textContent || "";
    const card = (k) => { const c = document.querySelector(`[data-card="${k}"]`); return c ? { val: c.querySelector(".val").textContent, sub: c.querySelector(".s").textContent, tone: c.querySelector(".ind").dataset.tone } : null; };
    return { state: document.getElementById("panel").dataset.state, status: t("status-value"), lead: t("cycle-lead"), seeds: t("seeds-line"),
      cards: { trend: card("trend"), risk: card("risk"), confidence: card("confidence"), data_quality: card("data_quality") },
      vwcap: t("vw-cap"), vnActive: t("vn-active"), plValidators: t("pl-validators"), growthHidden: document.getElementById("vw-growth").hidden,
      body: document.body.innerText, scrollW: document.documentElement.scrollWidth, innerW: window.innerWidth };
  });
  await page.close();
  return out;
}

const scen = { capture: ["organism-capture-20261021T072727Z.json", "health-capture-20261021T072727Z.json"],
  seeds_only: ["organism-seeds_only.json", "health-seeds_only.json"], seed_and_validators: ["organism-seed_and_validators.json", "health-seed_and_validators.json"],
  validators_only: ["organism-validators_only.json", "health-validators_only.json"], insufficient: ["organism-insufficient.json", "health-insufficient.json"] };

console.log("\n[HOMEPAGE_PREVIEW] each scenario: values and reasons are /organism's");
for (const [name, [of, hf]] of Object.entries(scen)) {
  const o = load(of), h = load(hf);
  const r = await render(o, h);
  check(`${name}: status word is /organism.status`, r.status === String(o.status).toUpperCase(), r.status);
  for (const k of ["trend", "risk", "confidence", "data_quality"]) check(`${name}: ${k} card value is /organism.${k}`, r.cards[k] && r.cards[k].val === String(o[k]), JSON.stringify(r.cards[k]));
  const rf = Array.isArray(o.risk_factors) ? o.risk_factors.join(" · ") : "";
  check(`${name}: risk reason is /organism.risk_factors`, r.cards.risk.sub === rf, r.cards.risk.sub);
  check(`${name}: confidence reason is /organism.confidence_reason`, r.cards.confidence.sub === (o.confidence_reason || ""), r.cards.confidence.sub);
  check(`${name}: no 35 on the page unless a fixture field says 35`, /\b35\b/.test(JSON.stringify([o, h])) || !/\b35\b/.test(r.body), (r.body.match(/.{30}\b35\b.{30}/) || [])[0]);
  check(`${name}: no horizontal overflow at 1280`, r.scrollW <= r.innerW, r.scrollW);
}

console.log("\n[HOMEPAGE_PREVIEW] ADJ: adjacent cycles with identical labels are not one observation");
{
  const o = load(scen.seeds_only[0]), h = load(scen.seeds_only[1]);
  // Same words, a different round: /health 20 s earlier, different reasons.
  const h2 = JSON.parse(JSON.stringify(h));
  h2.observed_at = new Date(Date.parse(o.observed_at) - 20000).toISOString();
  h2.risk_factors = ["RISK FROM ANOTHER ROUND"]; h2.confidence_reason = "CONFIDENCE FROM ANOTHER ROUND";
  const r = await render(o, h2);
  check("ADJ1 the reasons shown are /organism's, not /health's", !r.body.includes("ANOTHER ROUND") && r.cards.risk.sub === (o.risk_factors || []).join(" · "), r.cards.risk.sub + " | " + r.cards.confidence.sub);
  check("ADJ2 the seeds line is built from /organism alone (no 'k of N configured seeds answered' from /health)", !/of \d configured seeds answered/.test(r.seeds), r.seeds);
  const same = await render(o, h);
  check("ADJ3 with equal observed_at the seeds line may carry /health's seed detail", /configured seeds/.test(same.seeds), same.seeds);
}

console.log("\n[HOMEPAGE_PREVIEW] NOOC: a /health without on_chain_validators retains nothing");
{
  const o = load(scen.seeds_only[0]), h = JSON.parse(JSON.stringify(load(scen.seeds_only[1])));
  delete h.on_chain_validators; delete h.validator_watch;
  const r = await render(o, h);
  check("NOOC1 the lead says not reported", /ACTIVE on chain: not reported/.test(r.lead), r.lead);
  check("NOOC2 the ACTIVE rung has no number", r.vnActive.trim() === "not reported", r.vnActive);
  check("NOOC3 no 35 anywhere, no 'one read'", !/\b35\b/.test(r.body) && !/one read/i.test(r.body), (r.body.match(/.{30}(\b35\b|one read).{30}/i) || [])[0]);
  check("NOOC4 the caption says why", /does not publish on_chain_validators/.test(r.vwcap), r.vwcap);
  check("NOOC5 the growth box is hidden", r.growthHidden === true);
}

console.log("\n[HOMEPAGE_PREVIEW] WATCH: the watch round has its own clock");
{
  const o = load(scen.seeds_only[0]), h = load(scen.seeds_only[1]);
  const r = await render(o, h);
  const w = h.validator_watch, oc = h.on_chain_validators;
  const hhmmss = (iso) => iso.slice(11, 19) + " UTC";
  if (w && w.state === "observed" && w.round_at) check("WATCH1 'watch round HH:MM:SS UTC' is shown from validator_watch.round_at", r.vwcap.includes("watch round " + hhmmss(w.round_at)), r.vwcap);
  else check("WATCH1 (watch not observed in this fixture) no watch clock is shown", !/watch round/.test(r.vwcap), r.vwcap);
  if (oc && oc.observed_at) check("WATCH2 'List read HH:MM:SS UTC' is from on_chain_validators.observed_at", r.vwcap.includes("List read " + hhmmss(oc.observed_at)), r.vwcap);
}

console.log("\n[HOMEPAGE_PREVIEW] FAIL: a failed /organism read is said as a failure to read");
{
  const r = await render(null, load(scen.seeds_only[1]));
  check("F1 status unknown, 'failure to read, not an observation about the network'", r.status === "UNKNOWN" && /failure to read/.test(r.seeds), r.seeds);
}

await browser.close(); server.close();
console.log("\n[HOMEPAGE_PREVIEW] " + passed + " passed, " + failed + " failed");
process.exit(failed ? 1 : 0);
